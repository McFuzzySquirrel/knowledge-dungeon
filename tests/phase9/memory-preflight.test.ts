const ENFORCER = path.join(REPO_ROOT, 'scripts', 'check-memory.mjs');
const enforcerSource = sourceOf('scripts/check-memory.mjs');

/** ~200 KiB of incompressible bytes: a chunk well under the ceiling, well over zero. */
const SMALL_RENDERER_BYTES = incompressible(200_000, 3);
/** ~900 KiB of incompressible bytes: over the 800 KiB gzip ceiling once gzipped. */
const HUGE_RENDERER_BYTES = incompressible(900_000, 5);

describe('the plan numbers are the ones the plan states', () => {
  it('pins the 800 KiB gzip lazy-chunk ceiling as integer bytes', () => {
    expect(LAZY_CHUNK_GZIP_BYTES).toBe(819_200);
    expect(LAZY_CHUNK_GZIP_KIB).toBe(800);
    expect(enforcerSource).toMatch(/LAZY_CHUNK_GZIP_BYTES\s*=\s*800 \* 1024/);
    expect(enforcerSource).toContain('Any lazy JavaScript chunk: no more than 800 KB gzip.');
    // The ceiling is otherwise unenforced: `check-bundle-size.mjs` allows 2.5 MB *raw*
    // per chunk, which is roughly 800 KB uncompressed, so today a renderer bundle
    // can reach twice the plan's gzip budget with no gate noticing.
    const bundleGuard = sourceOf('scripts/check-bundle-size.mjs');
    expect(bundleGuard).toContain('MAX_CHUNK_BYTES = 2_500_000');
  });

  it('records the plan section and the cycle count the browser lane will need', () => {
    expect(enforcerSource).toContain('plan section 10.2');
    expect(MOUNT_UNMOUNT_CYCLES).toBe(20);
    expect(enforcerSource).toMatch(/MOUNT_UNMOUNT_CYCLES\s*=\s*20/);
  });

  it('is deterministic: a stated gzip level, no clock, no randomness, no server', () => {
    expect(enforcerSource).toMatch(/GZIP_LEVEL\s*=\s*9/);
    expect(gzipSize(Buffer.from('a'.repeat(10_000), 'utf8'))).toBe(
      fixtureGzipSize(Buffer.from('a'.repeat(10_000), 'utf8')),
    );
    for (const forbidden of [/\bDate\b/, /Math\.random/, /localhost/, /createServer/, /127\.0\.0\.1/]) {
      expect(enforcerSource, String(forbidden)).not.toMatch(forbidden);
    }
    expect(enforcerSource).not.toMatch(/require\(/);
    const imports = [...enforcerSource.matchAll(/^import .* from '([^']+)';/gm)].map((match) => match[1]);
    expect(imports.length).toBeGreaterThan(0);
    for (const specifier of imports) expect(specifier, specifier).toMatch(/^node:/);
  });
});

describe('the entry document resolves to a set of initial files, and a dangling one is a problem', () => {
  it('collects module scripts, modulepreloads, and stylesheets once each', () => {
    const { initial, nomodule, problems } = collectInitialAssets(
      entryHtml({
        modules: ['index-a1.js', 'index-a1.js'],
        modulepreloads: ['vendor-react-b2.js', 'index-a1.js'],
        styles: ['index-c3.css'],
        nomodules: ['index-legacy-d4.js'],
      }),
    );
    expect(problems).toEqual([]);
    expect([...initial.keys()].sort()).toEqual([
      'assets/index-a1.js',
      'assets/index-c3.css',
      'assets/vendor-react-b2.js',
    ]);
    // Referenced by two kinds, counted once, and both kinds recorded.
    expect([...(initial.get('assets/index-a1.js')?.kinds ?? [])].sort()).toEqual([
      'js-module',
      'js-modulepreload',
    ]);
    // The ES5 fallback is collected separately, not folded into the initial set. It is
    // what a browser without module support downloads, and plan section 10.2 declines
    // to count it, so folding it in would report a finding in a browser the plan does
    // not support as if it were one in the browsers it does.
    expect([...nomodule.keys()]).toEqual(['assets/index-legacy-d4.js']);
    expect(nomodule.get('assets/index-legacy-d4.js')?.kinds).toEqual(['js-nomodule']);
  });

  it('does not treat a `nomodule` renderer chunk as an eager Pixi load', () => {
    const { initial, nomodule } = collectInitialAssets(
      entryHtml({ modules: ['index-a1.js'], nomodules: ['vendor-pixi-legacy-b2.js'] }),
    );
    const result = evaluateMemoryPreflight({
      chunks: [{ path: 'assets/vendor-pixi-legacy-b2.js', family: 'vendor-pixi', rawBytes: 10, gzipBytes: 10 }],
      assetsDirPresent: true,
      entryPaths: new Set(initial.keys()),
    });
    expect(nomodule.has('assets/vendor-pixi-legacy-b2.js')).toBe(true);
    expect(result.ok).toBe(true);
  });

  it('rejects a reference that leaves the artifact rather than counting it', () => {
    expect(resolveInitialPath('https://cdn.example.invalid/a.js')).toBeUndefined();
    expect(resolveInitialPath('//cdn.example.invalid/a.js')).toBeUndefined();
    expect(resolveInitialPath('/assets/../../etc/passwd')).toBeUndefined();
    expect(resolveInitialPath('/assets/index-a1.js?v=2')).toBe('assets/index-a1.js');
    const { problems } = collectInitialAssets(
      entryHtml({ remote: ['https://cdn.example.invalid/a.js'] }),
    );
    expect(problems).toHaveLength(1);
    expect(problems[0]).toContain('does not name a file inside the built artifact');
  });

  it('resolves a renderer family from the basename, never from a hash', () => {
    expect(rendererChunkFamily('assets/vendor-pixi-CkHy5qFN.js')).toBe('vendor-pixi');
    expect(rendererChunkFamily('assets/vendor-pixi-legacy-CD2.js')).toBe('vendor-pixi');
    expect(rendererChunkFamily('assets/vendor-phaser-BHvTOz-D.js')).toBe('vendor-phaser');
    expect(rendererChunkFamily('assets/index-CANyR14L.js')).toBeUndefined();
    expect(Object.keys(RENDERER_CHUNK_FAMILIES).sort()).toEqual(['vendor-phaser', 'vendor-pixi']);
  });
});

describe('the preflight decides pass or fail from a measurement', () => {
  const lazy = { path: 'assets/vendor-pixi-a1.js', family: 'vendor-pixi', rawBytes: 200_000, gzipBytes: 199_000 };

  it('passes a lazy Pixi chunk that is within the ceiling', () => {
    const result = evaluateMemoryPreflight({
      chunks: [lazy],
      assetsDirPresent: true,
      entryPaths: new Set(['assets/index-a1.js']),
    });
    expect(result.ok).toBe(true);
    expect(result.findings).toEqual([]);
    expect(result.byFamily['vendor-pixi'].eagerPaths).toEqual([]);
    expect(result.measuredCount).toBe(1);
  });

  it('fails an eager Pixi chunk, and says which chunk and which rule', () => {
    const result = evaluateMemoryPreflight({
      chunks: [lazy],
      assetsDirPresent: true,
      entryPaths: new Set(['assets/index-a1.js', 'assets/vendor-pixi-a1.js']),
    });
    expect(result.ok).toBe(false);
    expect(result.findings.map((finding) => finding.code)).toEqual(['eager-pixi']);
    expect(result.findings[0].message).toContain('assets/vendor-pixi-a1.js');
    expect(result.findings[0].message).toContain('Plan section 10.2');
  });

  it('reports an eager Phaser chunk without failing, because it is pre-existing and Phase 24 owns it', () => {
    const result = evaluateMemoryPreflight({
      chunks: [{ path: 'assets/vendor-phaser-b2.js', family: 'vendor-phaser', rawBytes: 10, gzipBytes: 10 }],
      assetsDirPresent: true,
      entryPaths: new Set(['assets/vendor-phaser-b2.js']),
    });
    expect(result.ok).toBe(true);
    expect(result.byFamily['vendor-phaser'].eagerPaths).toEqual(['assets/vendor-phaser-b2.js']);
  });

  it('fails a renderer chunk over the plan ceiling', () => {
    const result = evaluateMemoryPreflight({
      chunks: [{ path: 'assets/vendor-pixi-a1.js', family: 'vendor-pixi', rawBytes: 900_000, gzipBytes: LAZY_CHUNK_GZIP_BYTES + 1 }],
      assetsDirPresent: true,
      entryPaths: new Set(),
    });
    expect(result.ok).toBe(false);
    expect(result.findings.map((finding) => finding.code)).toEqual(['oversized-renderer']);
    expect(result.findings[0].message).toContain('800 KiB ceiling');
  });

  it('fails an artifact with no renderer chunk at all, rather than reporting nothing', () => {
    // The failure mode this gate exists to prevent, restated at the unit level: a
    // green run that measured nothing.
    const result = evaluateMemoryPreflight({
      chunks: [],
      assetsDirPresent: true,
      entryPaths: new Set(['assets/index-a1.js']),
    });
    expect(result.ok).toBe(false);
    expect(result.findings.map((finding) => finding.code)).toEqual(['no-renderer-chunk']);
  });

  it('fails an artifact with no assets tree at all', () => {
    const result = evaluateMemoryPreflight({ chunks: [], assetsDirPresent: false, entryPaths: new Set() });
    expect(result.ok).toBe(false);
    expect(result.findings.map((finding) => finding.code)).toEqual(['no-assets-tree']);
  });
});

describe('a family it does not know is a finding, not a TypeError', () => {
  it('reports an undeclared family and still returns a verdict', () => {
    // `MeasuredRendererChunk.family` is `string` in the declaration, so this input is
    // legal by the function's own types. The bug this holds shut was a `TypeError` at
    // `RENDERER_CHUNK_FAMILIES[family].renderer`, on the same line of code that
    // reports findings in sentence form - the gate contradicting its own stated rule
    // for the reader who needed the sentence.
    const result = evaluateMemoryPreflight({
      chunks: [
        { path: 'assets/vendor-mystery-a1.js', family: 'vendor-mystery', rawBytes: 10, gzipBytes: 10 },
      ],
      assetsDirPresent: true,
      entryPaths: new Set(),
    });
    expect(result.findings.map((finding) => finding.code)).toEqual(['unknown-renderer-family']);
    expect(result.findings[0].message).toContain('vendor-mystery');
    expect(result.findings[0].message).toContain('RENDERER_CHUNK_FAMILIES');
    expect(result.ok).toBe(false);
    // And the census still accounts for it, rather than dropping a measured chunk.
    expect(result.measuredCount).toBe(1);
    expect(result.byFamily['vendor-mystery'].renderer).toBe('vendor-mystery');
  });

  it('does not throw for any string, including the empty one and a prototype key', () => {
    // The two values a registry lookup most easily dies on: an empty string, and a
    // key that exists on `Object.prototype` and would be found by `in`.
    for (const family of ['', 'toString', 'constructor', 'vendor-pixi/../vendor-phaser', 'VENDOR-PIXI']) {
      const call = () =>
        evaluateMemoryPreflight({
          chunks: [{ path: 'assets/x-a1.js', family, rawBytes: 1, gzipBytes: 1 }],
          assetsDirPresent: true,
          entryPaths: new Set(),
        });
      expect(call, family).not.toThrow();
      expect(call().findings.map((finding) => finding.code), family).toContain('unknown-renderer-family');
    }
  });

  it('an inherited property is not a declared family, because a registry lookup must use hasOwnProperty', () => {
    expect(isDeclaredRendererFamily('vendor-pixi')).toBe(true);
    expect(isDeclaredRendererFamily('toString')).toBe(false);
    expect(isDeclaredRendererFamily('__proto__')).toBe(false);
  });

  it('the declaration is what the runtime consults, and every family carries both prose fields', () => {
    // If a family were added without an `absence` line, the report would print
    // `undefined` in the exact place that exists to keep a reader from mistaking
    // absence for a measurement.
    expect(RENDERER_FAMILY_NAMES).toEqual(Object.keys(RENDERER_CHUNK_FAMILIES));
    for (const family of RENDERER_FAMILY_NAMES) {
      const entry = RENDERER_CHUNK_FAMILIES[family];
      expect(entry.reason.length, `${family}.reason`).toBeGreaterThan(20);
      expect(entry.absence.length, `${family}.absence`).toBeGreaterThan(20);
    }
  });
});

describe('absence is reported per family, and never counted as a measurement', () => {
  const phaserOnly = {
    chunks: [{ path: 'assets/vendor-phaser-b2.js', family: 'vendor-phaser', rawBytes: 10, gzipBytes: 10 }],
    assetsDirPresent: true,
    entryPaths: new Set<string>(),
  };

  it('names the absent family, and says the Pixi verdict was not established here', () => {
    // The default production build. It passes, and it measured Phaser. It did not
    // measure Pixi, and the two states have to be distinguishable in the result and
    // not only in the prose.
    const result = evaluateMemoryPreflight(phaserOnly);
    expect(result.ok).toBe(true);
    expect(result.families).toEqual(['vendor-phaser']);
    expect(result.measuredFamilies).toEqual(['Phaser']);
    expect(result.absentFamilies).toEqual(['PixiJS']);
    expect(result.familiesReport.map((entry) => [entry.family, entry.present])).toEqual([
      ['vendor-phaser', true],
      ['vendor-pixi', false],
    ]);
    // An absent family is a reported fact, not a finding - otherwise the default
    // build could never pass its own gate.
    expect(result.findings).toEqual([]);
  });

  it('measures the family on the build that contains it, and the report is symmetric', () => {
    const pixiBuild = evaluateMemoryPreflight({
      chunks: [{ path: 'assets/vendor-pixi-b2.js', family: 'vendor-pixi', rawBytes: 10, gzipBytes: 10 }],
      assetsDirPresent: true,
      entryPaths: new Set(),
    });
    expect(pixiBuild.measuredFamilies).toEqual(['PixiJS']);
    expect(pixiBuild.absentFamilies).toEqual(['Phaser']);
    expect(pixiBuild.byFamily['vendor-pixi'].eagerPaths).toEqual([]);
  });

  it('a family with no chunk reports zero measurement and present: false, not a clean family', () => {
    const absent = evaluateMemoryPreflight({ chunks: [], assetsDirPresent: true, entryPaths: new Set() })
      .familiesReport.find((entry) => entry.family === 'vendor-pixi');
    expect(absent).toMatchObject({ present: false, chunks: [], rawBytes: 0, gzipBytes: 0, eagerPaths: [] });
  });

  it('the CLI prints the absence on the default build and enumerates the measured families on a pass', () => {
    const dist = writeSyntheticDist(
      { modules: ['index-a1.js'] },
      { 'index-a1.js': filler(2_000), 'vendor-phaser-b2.js': SMALL_RENDERER_BYTES },
    );
    const run = runNode(ENFORCER, [`--dist=${dist}`]);
    expect(run.code, run.output).toBe(0);
    expect(run.output).toContain('vendor-pixi (PixiJS) - NOT PRESENT in this build');
    expect(run.output).toContain('No PixiJS chunk in this artifact, so nothing about it was measured.');
    expect(run.output).toContain('Renderer families NOT measured on this artifact (absent from it, not clean): PixiJS');
    expect(run.output).toContain('Measured for eager load: Phaser.');
    expect(run.output).toContain('NOT measured on this artifact (absent from it, so not clean either): PixiJS');
    // The old closing sentence claimed the Pixi verdict for this artifact. It must
    // not be back: on a build with no Pixi chunk the claim is about the build.
    expect(run.output).not.toContain('2 renderer chunk(s) measured, no eager Pixi chunk, all within');
  });

  it('and the Pixi build measures Pixi rather than reporting its absence', () => {
    const dist = writeSyntheticDist(
      { modules: ['index-a1.js'] },
      { 'index-a1.js': filler(2_000), 'vendor-pixi-b2.js': SMALL_RENDERER_BYTES },
    );
    const run = runNode(ENFORCER, [`--dist=${dist}`]);
    expect(run.code, run.output).toBe(0);
    expect(run.output).toContain('vendor-pixi (PixiJS) - measured');
    expect(run.output).toContain('Measured for eager load: PixiJS.');
    expect(run.output).toContain('NOT measured on this artifact (absent from it, so not clean either): Phaser.');
    // The Pixi measurement is real here, and the report does not need to hedge it.
    expect(run.output).not.toContain('"no eager Pixi load on Welcome" is established on the');
  });
});

