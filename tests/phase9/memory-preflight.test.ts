/**
 * `scripts/check-memory.mjs`: the deterministic half of plan section 10.2's renderer
 * memory gate, and an honest account of the half that is not deterministic.
 *
 * ## Why this file exists
 *
 * Plan line 4198 lists `npm run check:memory` in Phase 9's verification block, and no
 * such script existed: `grep check:memory package.json` returned nothing. The phase was
 * unbuildable as written. This file covers the script that closes that gap.
 *
 * ## The honesty half
 *
 * Plan section 10.2 asks for "no material canvas or GPU memory growth over 20 world
 * mount and unmount cycles". That is a runtime property and cannot be read out of a
 * directory of files. So the assertions here are split in two, and both halves are
 * pinned:
 *
 * - The measurements the script *can* make - no eager Pixi chunk in the entry
 *   document, plan section 10.2's 800 KiB gzip ceiling for any lazy chunk, a
 *   coherent artifact, a non-vacuous run - are exercised against synthetic trees, so
 *   each one is shown to fail on a tree that violates it and pass on one that does not.
 * - The measurements it *cannot* make are asserted as an explicit, printed statement,
 *   so a reader of a green run cannot mistake this preflight for a leak measurement.
 *
 * The second half is the part worth defending. A build-level check dressed as a
 * memory check is worse than no check, because it is read as coverage. `NOT MEASURED`
 * is asserted to be non-empty, to name canvas count, GPU memory, heap, and context
 * loss, and to be printed on every run including the passing one.
 *
 * ## Hermeticity
 *
 * Every fixture is a synthetic `dist` written into a temp directory outside the
 * repository and passed with `--dist=`, so nothing here depends on a build having run,
 * on the checkout's history, or on where the checkout lives on disk. The same bytes
 * measured from two different working directories must produce two identical reports,
 * which is the Phase 8 defect this repo has already paid for once.
 *
 * Privacy: the fixtures contain generated bytes and a hand-written HTML document. No
 * subject, note, attachment, progression, statistic, or preference appears in any of
 * them, and nothing here writes inside the repository.
 */

