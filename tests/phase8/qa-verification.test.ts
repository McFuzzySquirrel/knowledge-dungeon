/**
 * The four legacy theme blocks as they were before Phase 8, read from a committed
 * fixture.
 *
 * Deliberately *not* read from the checkout's own history, which is the defect this
 * replaces. `git show HEAD:src/styles.css` is only the pre-Phase-8 file while
 * `HEAD` still predates the change: the moment the change is committed, `HEAD` *is*
 * the new stylesheet, the gate compares the file against itself, and it finds zero
 * differences where the exit criterion requires exactly three. That is how a gate
 * passes in the author's working tree and fails in a checkout of the committed state
 * - the same defect class Phase 7 recorded twice, once as a `git show` against a sha
 * an `actions/checkout@v4` depth-1 clone does not have.
 *
 * The fixture follows `tests/phase7/support/fixtures/`: a header recording where the
 * bytes came from, a sentinel, and a digest of its own body that is re-derived on
 * every read. So the baseline cannot drift into agreeing with whatever the working
 * tree currently is, and no assertion here depends on clone depth, on a sha staying
 * resolvable, or on where the checkout lives.
 */
const BASELINE_PATH = path.join(
  REPO_ROOT,
  'tests',
  'phase8',
  'support',
  'fixtures',
  'pre-phase8-legacy-theme-blocks.css.fixture',
);
const BASELINE_SENTINEL = '/* __P8_LEGACY_THEME_BODY_BELOW__ */';

const ROOT_SELECTOR = ':root {';
const LIGHT_SELECTOR = ".ui-skin[data-theme='light'] {";
const COLORFUL_SELECTOR = ".ui-skin[data-theme='colorful'] {";
const AURORA_SELECTOR = ".ui-skin[data-theme='aurora'] {";
const LEGACY_SELECTORS = [ROOT_SELECTOR, LIGHT_SELECTOR, COLORFUL_SELECTOR, AURORA_SELECTOR];

/**
 * The two `font-family` declarations Phase 8 was permitted to change below the theme
 * blocks, and what they were.
 *
 * Named rather than pattern-matched: a "the only changed lines are font lines"
 * assertion is satisfiable by a change that is a font line, so the *values* are pinned
 * and the substituted result is checked against a digest of the pre-Phase-8 region.
 */
const LEGACY_WEB_MONO_STACK = "  font-family: 'JetBrains Mono', ui-monospace, monospace;";
const LEGACY_LOCAL_MONO_STACK =
  "  font-family: ui-monospace, 'Cascadia Code', 'SFMono-Regular', Menlo, Consolas, 'DejaVu Sans Mono', monospace;";
const LEGACY_LOCAL_MONO_STACK_LINES = 2;

/**
 * The pre-Phase-8 `src/styles.css` from the closing `}` of the last theme block to the
 * end of the file, pinned by digest and by length.
 *
 * Storing a second copy of these 5,813 lines in a fixture would make every future
 * stylesheet edit a 5,800-line diff in `tests/` rather than a one-line reviewed
 * decision, and the digest enforces the same property. The assertion does not compare
 * against a frozen copy of today: it reverts the two permitted font lines and requires
 * the result to hash to the *pre-Phase-8* digest, which is the "nothing else changed"
 * claim stated rather than frozen.
 */
const LEGACY_TAIL_SHA256 = '25d19351afcefc78e16f7487b33cf9c639e6ff732f1dfe8543bab4ceeb109145';
const LEGACY_TAIL_LINES = 5813;
const LEGACY_TAIL_BYTES = 125_252;

/**
 * Unique custom properties the whole stylesheet declares, excluding the font stacks.
 *
 * Subsumed by the block comparison and the tail digest, and kept because a red run
 * should say how many legacy declarations are in play.
 */
const LEGACY_PROPERTY_COUNT = 32;

function sha256(text: string): string {
  return createHash('sha256').update(text, 'utf8').digest('hex');
}

/** `[firstLineIndex, closingBraceLineIndex]`, or `null` when the selector is absent. */
function blockBounds(source: string, selector: string): [number, number] | null {
  const lines = source.split('\n');
  const index = lines.findIndex((line) => line.trim() === selector);
  if (index === -1) return null;
  let end = index + 1;
  while (end < lines.length && lines[end].trim() !== '}') end += 1;
  if (end === lines.length) return null;
  return [index, end];
}

function blockRange(source: string, selector: string): string | null {
  const bounds = blockBounds(source, selector);
  if (bounds === null) return null;
  return source.split('\n').slice(bounds[0], bounds[1] + 1).join('\n');
}

/** Everything after the last theme block: the region the tail digest covers. */
function legacyTail(source: string, what: string): string {
  const bounds = blockBounds(source, AURORA_SELECTOR);
  if (bounds === null) throw new Error(`${what} has no ${AURORA_SELECTOR} block`);
  return source.split('\n').slice(bounds[1] + 1).join('\n');
}

interface BaselineFixture {
  header: string;
  body: string;
  measuredSha256: string;
  measuredBytes: number;
  declaredSha256: string;
  declaredBytes: number;
  declaredPath: string;
  declaredCommit: string;
  declaredShortCommit: string;
}

/**
 * Reads the baseline fixture and re-derives its digest.
 *
 * Throws rather than returning a partial fixture: a reader that quietly handed back a
 * degraded baseline would let a corrupted snapshot pass the byte-identity comparison,
 * which is the one thing the fixture exists to prevent.
 */
function readBaselineFixture(): BaselineFixture {
  const raw = readFileSync(BASELINE_PATH, 'utf8');
  const marker = raw.indexOf(BASELINE_SENTINEL);
  if (marker < 0) throw new Error(`${BASELINE_PATH} has no ${BASELINE_SENTINEL} line`);
  const split = raw.indexOf('\n', marker);
  if (split < 0) throw new Error(`${BASELINE_PATH} ends at its sentinel line and has no body`);
  const header = raw.slice(0, split);
  const body = raw.slice(split + 1);
  const declaration = (pattern: RegExp, what: string): RegExpExecArray => {
    const match = pattern.exec(header);
    if (match === null) {
      throw new Error(`${BASELINE_PATH} has no "${what}" declaration in its header`);
    }
    return match;
  };
  return {
    header,
    body,
    measuredSha256: sha256(body),
    measuredBytes: Buffer.byteLength(body, 'utf8'),
    declaredSha256: declaration(
      /^\s*\*\s+Captured as\s+:\s+\d+\s+bytes,\s+sha256\s+([0-9a-f]{64})\s*$/m,
      'Captured as',
    )[1] as string,
    declaredBytes: Number.parseInt(
      declaration(/^\s*\*\s+Captured as\s+:\s+(\d+)\s+bytes\b/m, 'Captured as')[1] as string,
      10,
    ),
    declaredPath: declaration(/^\s*\*\s+Source path\s+:\s+(\S+)\s*$/m, 'Source path')[1] as string,
    declaredCommit: declaration(
      /^\s*\*\s+Taken from\s+:\s+commit\s+([0-9a-f]{40})\b[^\n]*\bshort form\s+([0-9a-f]{7,40})\b/m,
      'Taken from',
    )[1] as string,
    declaredShortCommit: declaration(
      /^\s*\*\s+Taken from\s+:\s+commit\s+([0-9a-f]{40})\b[^\n]*\bshort form\s+([0-9a-f]{7,40})\b/m,
      'Taken from',
    )[2] as string,
  };
}

describe('rolling VITE_COZY_VISUALS back leaves the legacy themes byte-identical', () => {
  const baseline = readBaselineFixture();
  const after = readFileSync(STYLES_PATH, 'utf8');
  const tail = legacyTail(after, STYLES_PATH);

  it('the baseline is a self-verifying fixture, so it cannot be edited into agreeing with the tree', () => {
    // Three things have to be true of the "before" or nothing below it means anything:
    // the fixture's bytes are the ones its header declares, the header says where they
    // came from, and the bytes are genuinely pre-Phase-8 rather than a copy of today.
    expect(baseline.measuredSha256, 'the baseline body no longer hashes to its declared digest').toBe(
      baseline.declaredSha256,
    );
    expect(baseline.measuredBytes).toBe(baseline.declaredBytes);
    expect(baseline.declaredPath).toBe('src/styles.css');
    expect(baseline.declaredCommit).toMatch(/^[0-9a-f]{40}$/);
    expect(baseline.declaredCommit.startsWith(baseline.declaredShortCommit)).toBe(true);
    // A fixture regenerated from the working tree would satisfy every comparison below
    // while asserting nothing, and this is the line that says so.
    for (const webFont of ["'Cinzel'", "'JetBrains Mono'", "'Inter'"]) {
      expect(baseline.body, `the baseline is missing ${webFont}, so it is not the pre-Phase-8 file`).toContain(
        webFont,
      );
    }
    expect(after, 'the working stylesheet still names a web font in a theme block').not.toMatch(
      /'Cinzel'|'JetBrains Mono'|'Inter'/,
    );
  });

  it('the baseline holds exactly the four theme blocks and nothing else', () => {
    // The point of the fixture is to be a minimal, reviewable "before". A block added
    // to it would widen what "unchanged" is measured against without anyone reading it.
    const openers = baseline.body
      .split('\n')
      .filter((line) => line.trimEnd().endsWith('{'))
      .map((line) => line.trim());
    expect(openers).toEqual(LEGACY_SELECTORS);
    expect(baseline.body.split('\n').filter((line) => line.trim() === '}')).toHaveLength(4);
  });

  it.each([LIGHT_SELECTOR, COLORFUL_SELECTOR, AURORA_SELECTOR])(
    '%s is byte-identical to its pre-Phase-8 value',
    (selector) => {
      expect(blockRange(after, selector), `${selector} is missing`).toBe(
        blockRange(baseline.body, selector),
      );
    },
  );

  it('the only change in :root is the three font-stack lines the criterion requires', () => {
    const was = blockRange(baseline.body, ROOT_SELECTOR);
    const now = blockRange(after, ROOT_SELECTOR);
    expect(was, ':root is missing from the baseline').not.toBeNull();
    expect(now, ':root is missing').not.toBeNull();

    const wasLines = (was as string).split('\n');
    const nowLines = (now as string).split('\n');
    expect(nowLines, ':root changed length').toHaveLength(wasLines.length);

    const changed: string[] = [];
    for (let index = 0; index < wasLines.length; index += 1) {
      if (wasLines[index] !== nowLines[index]) changed.push(wasLines[index]);
    }
    // Every legacy colour token in :root has to be exactly as it was. The
    // criterion that requires the change is the no-remote-font one, and the
    // remote font is the only thing in :root that has to go.
    expect(changed, 'a non-font declaration in :root changed').toHaveLength(3);
    for (const line of changed) {
      expect(line).toMatch(/^\s*--?font-[a-z]+:|^\s*font-family:/);
    }
    const removed = changed.map((line) => /:\s*(.+);\s*$/.exec(line)?.[1] ?? '').join(' | ');
    const added = (now as string)
      .split('\n')
      .filter((line, index) => wasLines[index] !== line)
      .map((line) => /:\s*(.+);\s*$/.exec(line)?.[1] ?? '')
      .join(' | ');
    // None of the three may retain a web font, which is the whole point.
    for (const family of [added]) {
      expect(family).not.toMatch(/Cinzel|JetBrains|(^|,\s*)'Inter'/);
      expect(family).not.toMatch(/https?:/);
    }
    expect(removed.length).toBeGreaterThan(0);
  });

  it('no legacy colour value anywhere in the stylesheet changed', () => {
    // A belt-and-braces pass over every custom property declared in the four
    // legacy blocks, so a value edited outside :root cannot pass unnoticed.
    const declarations = (source: string): Map<string, string> => {
      const map = new Map<string, string>();
      for (const line of source.split('\n')) {
        const match = /^\s*(--[a-z0-9-]+):\s*(.+);\s*$/.exec(line);
        if (match && !/^--font|^font-family/.test(match[1])) map.set(match[1], match[2]);
      }
      return map;
    };
    const baselineDeclarations = declarations(baseline.body);
    const nowDeclarations = declarations(after);
    for (const selector of LEGACY_SELECTORS) {
      const wasBlock = declarations(blockRange(baseline.body, selector) ?? '');
      const nowBlock = declarations(blockRange(after, selector) ?? '');
      expect([...nowBlock.keys()].sort(), `${selector} lost a declaration`).toEqual(
        [...wasBlock.keys()].sort(),
      );
      for (const [property, value] of wasBlock) {
        expect(nowBlock.get(property), `${selector} ${property}`).toBe(value);
      }
    }
    // The whole stylesheet still declares the legacy palette, so a "no change"
    // reading cannot come from a file that stopped declaring it.
    expect(baselineDeclarations.size).toBe(LEGACY_PROPERTY_COUNT);
    expect(nowDeclarations.size).toBe(LEGACY_PROPERTY_COUNT);
  });

  it('below the theme blocks, only the two web font-family lines changed', () => {
    // The 5,813 remaining lines, checked as the claim rather than as a frozen copy of
    // today: put the two web-font declarations back and the result must be the
    // pre-Phase-8 region, byte for byte. A colour edited anywhere below the theme
    // blocks, an added line, a reordered rule - all of them change the digest.
    const reverted = tail.split(LEGACY_LOCAL_MONO_STACK).join(LEGACY_WEB_MONO_STACK);
    expect(tail.split('\n').filter((line) => line === LEGACY_LOCAL_MONO_STACK)).toHaveLength(
      LEGACY_LOCAL_MONO_STACK_LINES,
    );
    expect(reverted, 'the permitted font replacement did not apply').not.toBe(tail);
    expect(tail.split('\n'), 'the stylesheet gained or lost lines below the theme blocks').toHaveLength(
      LEGACY_TAIL_LINES,
    );
    expect(Buffer.byteLength(reverted, 'utf8'), 'the region changed length').toBe(LEGACY_TAIL_BYTES);
    expect(
      sha256(reverted),
      'a declaration below the theme blocks changed other than the two web font-family lines',
    ).toBe(LEGACY_TAIL_SHA256);
    // And the no-remote-font criterion holds down there too, not only in :root.
    expect(tail).not.toMatch(/Cinzel|JetBrains|(^|[^\w-])'Inter'|fonts\.(googleapis|gstatic)|@font-face/);
  });

  it('the pre-Phase-8 Google Fonts import is gone and nothing remote replaced it', () => {
    // The region the block comparison and the tail digest leave least covered: the
    // prologue above :root, where the pre-Phase-8 file had the Google Fonts comment
    // and its `@import url(...)`. Phase 8 replaced that pair with its own header and
    // two local imports. The whole stylesheet is scanned as well, comments excluded,
    // so the claim is "no active remote origin anywhere in the file" rather than
    // "the two imports at the top look local".
    const before = blockBounds(after, ROOT_SELECTOR);
    expect(before, ':root is missing').not.toBeNull();
    const prologue = after.split('\n').slice(0, (before as [number, number])[0]).join('\n');
    const imports = prologue
      .split('\n')
      .map((line) => line.trim())
      .filter((line) => line.startsWith('@import'));
    expect(imports, 'the prologue has no imports at all').toHaveLength(2);
    for (const statement of imports) {
      expect(statement).toMatch(/^@import\s+'\.\//);
      expect(statement).not.toMatch(/url\(|https?:|\/\//);
    }
    const active = after.replace(/\/\*[\s\S]*?\*\//g, '');
    for (const forbidden of [
      /@font-face/,
      /\burl\(/,
      /\bhttps?:\/\//,
      /fonts\.(googleapis|gstatic)/,
      /'Cinzel'/,
      /'JetBrains Mono'/,
      /'Inter'/,
    ]) {
      expect(active, `src/styles.css still contains ${forbidden}`).not.toMatch(forbidden);
    }
  });
});

