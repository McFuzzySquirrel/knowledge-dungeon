/* 3. The published registry carries no learner data.                          */
/* ========================================================================== */

interface RegistryEntry {
  id?: unknown;
  path?: unknown;
  classification?: unknown;
  media?: unknown;
  [key: string]: unknown;
}
interface Registry {
  [key: string]: unknown;
  assets?: RegistryEntry[];
}

describe('the publicly served media registry carries no learner data', () => {
  const registry = JSON.parse(readFileSync(REGISTRY_PATH, 'utf8')) as Registry;
  const entries = registry.assets ?? [];

  it('is registered as a non-media repository file, so it is not a Pixi bundle member', () => {
    const self = entries.filter((entry) => entry.path === 'public/assets/asset-licenses.json');
    expect(self).toHaveLength(1);
    expect(self[0].classification).toBe('repository-authored');
    expect(self[0].media).toBe(false);
    expect(self[0].bundles).toEqual([]);
    expect(self[0].pixiEligible).toBe(false);
  });

  it('uses a closed key vocabulary: paths, ids, license facts, checksums, commit shas', () => {
    // The vocabulary the checker declares is the vocabulary that is allowed. An
    // unknown key is how a field that has nothing to do with licensing would
    // arrive, and nothing else in the gate would notice.
    const allowedEntryKeys = new Set([
      'id', 'path', 'classification', 'media', 'title', 'role', 'notes',
      'license', 'licenseVerified', 'licenseUrl', 'licenseUnverifiedReason',
      'creator', 'source', 'sourceUrl', 'sourceUrlNotApplicable',
      'date', 'dateKind', 'sha256', 'checksumPolicy', 'generation',
      'modifications', 'introducedBy', 'modifiedBy', 'bundles', 'pixiEligible',
      'legacyRenderer', 'retention',
    ]);
    const allowedGenerationKeys = new Set([
      'script', 'command', 'recipe', 'embedMarker', 'semanticCheck', 'checksum',
    ]);
    const allowedCommitKeys = new Set(['commit', 'date', 'subject']);
    const allowedSourceUrlKeys = new Set(['reason']);

    for (const entry of entries) {
      for (const key of Object.keys(entry)) {
        expect(allowedEntryKeys.has(key), `entry ${String(entry.id)} has key "${key}"`).toBe(true);
      }
      const generation = entry.generation as Record<string, unknown> | undefined;
      if (generation && typeof generation === 'object') {
        for (const key of Object.keys(generation)) {
          expect(
            allowedGenerationKeys.has(key),
            `entry ${String(entry.id)} generation has key "${key}"`,
          ).toBe(true);
        }
      }
      for (const commitField of ['introducedBy', 'modifiedBy'] as const) {
        const value = entry[commitField];
        const list = Array.isArray(value) ? value : value === undefined ? [] : [value];
        for (const commit of list) {
          if (commit && typeof commit === 'object') {
            for (const key of Object.keys(commit as Record<string, unknown>)) {
              expect(
                allowedCommitKeys.has(key),
                `entry ${String(entry.id)} ${commitField} has key "${key}"`,
              ).toBe(true);
            }
          }
        }
      }
      const notApplicable = entry.sourceUrlNotApplicable as Record<string, unknown> | undefined;
      if (notApplicable && typeof notApplicable === 'object') {
        for (const key of Object.keys(notApplicable)) {
          expect(
            allowedSourceUrlKeys.has(key),
            `entry ${String(entry.id)} sourceUrlNotApplicable has key "${key}"`,
          ).toBe(true);
        }
      }
    }
  });

  it('holds nothing shaped like a subject, a note, a room, an account, or a request', () => {
    // A vocabulary check cannot see a learner name typed into a `title` field, so
    // the values are scanned as well. The scan is restricted to the fields that
    // are *facts about an asset* rather than authored prose: `role`, `notes`,
    // `reason`, `recipe`, the `policy` block, and the per-theme descriptions are
    // descriptions this repository writes about itself, and they legitimately name
    // game concepts. A `sha256`, a `path`, an asset `id`, a `creator`, a
    // `sourceUrl`, a `date`, and a `commit` have no business holding anything but
    // the fact they name, so those are the fields the scan covers.
    const factFields = [
      'id', 'path', 'title', 'license', 'licenseUrl', 'licenseVerified', 'creator',
      'source', 'sourceUrl', 'date', 'dateKind', 'classification', 'media',
      'legacyRenderer', 'retention', 'checksumPolicy',
    ];
    const forbiddenValue = [
      /[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/, // an address
      /\b[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\b/i, // a UUID
      /\bBearer\s+[A-Za-z0-9._-]+/, // a credential
      /\b(lorem ipsum)\b/i,
      /\b(password|secret|api[_-]?key|auth[_-]?token)\b/i,
      // Identity vocabulary. Deliberately not the bare word "token": this file's
      // own vocabulary is design tokens, and a pattern that matched it would be a
      // test that could only be satisfied by renaming the system.
      /\b(learner|student|username|nickname|guardian|parent email)\b/i,
    ];
    // `sha256` is a closed hex format, checked separately and exactly, because a
    // pattern scan of it would be theatre.
    const hex64 = /^[0-9a-f]{64}$/;

    for (const entry of entries) {
      for (const field of factFields) {
        const value = entry[field];
        if (typeof value !== 'string' || value.length === 0) continue;
        for (const pattern of forbiddenValue) {
          expect(
            pattern.test(value),
            `entry ${String(entry.id)} field ${field}: ${value.slice(0, 120)}`,
          ).toBe(false);
        }
      }
      if (typeof entry.sha256 === 'string') {
        expect(entry.sha256, `entry ${String(entry.id)} sha256`).toMatch(hex64);
      }
      // Commit facts: a short sha, or null for a generated file, and nothing else.
      for (const commitField of ['introducedBy'] as const) {
        const value = entry[commitField] as Record<string, unknown> | undefined;
        if (value && typeof value === 'object') {
          if (value.commit !== null && value.commit !== undefined) {
            expect(String(value.commit), `entry ${String(entry.id)} commit`).toMatch(
              /^[0-9a-f]{7,40}$/,
            );
          }
          if (value.date !== null && value.date !== undefined) {
            expect(String(value.date), `entry ${String(entry.id)} commit date`).toMatch(
              /^\d{4}-\d{2}-\d{2}$/,
            );
          }
          for (const pattern of forbiddenValue) {
            expect(
              pattern.test(String(value.subject ?? '')),
              `entry ${String(entry.id)} ${commitField}.subject`,
            ).toBe(false);
          }
        }
      }
    }
    // And the whole document: no address, no UUID, and no credential anywhere,
    // including the prose, because those three cannot appear in prose either.
    const serialised = JSON.stringify(registry);
    expect(serialised, 'the registry contains an email-shaped value').not.toMatch(
      /[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/,
    );
    expect(serialised, 'the registry contains a UUID').not.toMatch(
      /\b[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\b/i,
    );
    expect(serialised, 'the registry contains a credential').not.toMatch(/\bBearer\s+/);
  });

  it('every path is a repository-relative asset path, so no absolute host is published', () => {
    for (const entry of entries) {
      const assetPath = String(entry.path);
      expect(assetPath.startsWith('public/assets/'), assetPath).toBe(true);
      expect(assetPath.startsWith('/'), assetPath).toBe(false);
      expect(assetPath).not.toContain('..');
      expect(assetPath).not.toMatch(/^[A-Za-z]:/);
    }
  });
});

