/* 1. The remote-font gate is bound, and it can fail.                          */
/* ========================================================================== */

describe('the remote-font gate has a failing state', () => {
  it('passes on an empty request list, which is what the default artifact must produce', () => {
    expect(countRemoteFontRequests([])).toBe(0);
    expect(() => assertNoRemoteFontRequests([])).not.toThrow();
  });

  it('FAILS when a recognised legacy font request is present - the negative control', () => {
    // The same exported function the Playwright test calls. If this does not
    // throw, the shipped assertion cannot fail either, and Phase 8's exit
    // criterion is theatre.
    const observed = [
      { resourceType: 'stylesheet', method: 'GET', url: 'https://fonts.googleapis.invalid/css2' },
      { resourceType: 'font', method: 'GET', url: 'https://fonts.gstatic.invalid/x.woff2' },
    ];
    expect(countRemoteFontRequests(observed)).toBe(2);
    expect(() => assertNoRemoteFontRequests(observed)).toThrow(
      /2 request\(s\) reached a recognised legacy static font host/,
    );
  });

  it('fails for a single request too, so there is no small count that slips through', () => {
    expect(() => assertNoRemoteFontRequests([{ resourceType: 'stylesheet' }])).toThrow();
  });

  it('names the plan criterion in the failure, so the red run says what broke', () => {
    const message = remoteFontRequestsFailureMessage([{ resourceType: 'font' }]);
    expect(message).toContain('Plan section 10.2');
    expect(message).toContain('must be zero');
    expect(message).toContain('font');
  });

  it('prints no hostname and no path, in the failure or in the exported helpers', () => {
    const observed = [
      { resourceType: 'stylesheet', url: 'https://fonts.googleapis.invalid/css2?family=Cinzel' },
    ];
    const message = remoteFontRequestsFailureMessage(observed);
    // A hostname, a path, and a query each have to be absent: the privacy suite
    // exists to prove there is no destination, so a failing run must not print one.
    expect(message).not.toMatch(/fonts\.(googleapis|gstatic)/);
    expect(message).not.toMatch(/https?:\/\//);
    expect(message).not.toContain('css2');
    expect(message).not.toContain('Cinzel');
    // And the module must not be able to reach a destination in the first place.
    expect(gateSource).not.toMatch(/new URL\(/);
    expect(gateSource).not.toMatch(/\.hostname/);
  });

  it('the Playwright spec actually applies the shipped predicate to the recorded requests', () => {
    // Text, not execution: the spec cannot be imported into vitest without
    // registering Playwright tests. Reading it is the same technique
    // `welcome-narrow-viewport.test.ts` uses, and it is what stops this control
    // from passing against a spec that kept recording the list but stopped
    // asserting on it.
    expect(specSource).toContain("from '../phase8/support/remoteFontGate'");
    expect(specSource).toContain('assertNoRemoteFontRequests');
    // Applied to the tolerance list, not to something derived: the assertion has
    // to be about exactly the requests the privacy spy chose not to report.
    expect(specSource).toMatch(
      /assertNoRemoteFontRequests\(\s*privacyReport\.blockedLegacyFontRequests/,
    );
    // The count is recorded before the assertion, so a red run still says how many.
    expect(specSource).toMatch(
      /countRemoteFontRequests\(\s*privacyReport\.blockedLegacyFontRequests/,
    );
    expect(specSource.indexOf('remoteFontRequestCount')).toBeLessThan(
      specSource.indexOf('assertNoRemoteFontRequests(privacyReport'),
    );
  });

  it('keeps the known-legacy tolerance, so a regression fails readably rather than anonymously', () => {
    // The tolerance is the reason the gate can name a font host at all. Removing
    // it would turn a reintroduced font import into an anonymous external-
    // destination failure in a suite premised on there being no external traffic.
    for (const host of ['fonts.googleapis.com', 'fonts.gstatic.com']) {
      expect(specSource, host).toContain(`'${host}'`);
    }
    const recognised = /knownLegacyFontHosts\s*=\s*new Set\(\[([^\]]*)\]\)/.exec(specSource)?.[1] ?? '';
    expect(recognised.split(',').filter((entry) => entry.trim().length > 0)).toHaveLength(
      KNOWN_LEGACY_FONT_HOST_COUNT,
    );
    expect(specSource).toContain('blockedLegacyFontRequests.push(observation)');
    // And the tolerance is not the whole privacy check: an unrecognised external
    // host is still a violation. The `else` is asserted rather than assumed,
    // because a tolerance with no fallback branch is a hole, not a gate.
    const toleranceBranch = /knownLegacyFontHosts\.has\(url\.hostname\)[\s\S]{0,220}?else\s*\{[\s\S]{0,220}?violations\.push/.exec(
      specSource,
    );
    expect(toleranceBranch, 'the known-legacy branch has no violation fallback').not.toBeNull();
  });
});

