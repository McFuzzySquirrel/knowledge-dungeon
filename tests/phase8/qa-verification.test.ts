/*
 * Closed since the Phase 8 QA pass: the gap this block used to document is closed
 * ---------------------------------------------------------------------------
 * This file's `MEDIA_EXTENSIONS` assertion pins the 25 extensions the checker treats
 * as media, and that count is unchanged. What changed is that the set is no longer the
 * only thing holding the rule together.
 *
 * The gap, as recorded then: an extension outside that set could be registered with
 * `media: false` and pass the gate, which is not the same as not being media. The QA
 * pass registered `.svgz`, `.aac`, `.oga`, `.opus`, `.apng`, `.jfif`, `.pjpeg`, `.glb`,
 * `.ktx2`, `.hdr`, `.exr`, `.dds`, `.basis`, `.wav2`, `.md`, and `.obj` as
 * `repository-authored` non-media and the gate exited 0 sixteen times, and an
 * unregistered one of those failed as `E-UNREGISTERED-FILE` rather than
 * `E-UNREGISTERED-MEDIA`. Both statements are now false.
 *
 * The extension vocabulary is closed instead. An extension is in `MEDIA_EXTENSIONS`, in
 * the declared `NON_MEDIA_EXTENSIONS` set, or unclassified - and unclassified is a
 * failure in every direction that can reach the build:
 *
 * - A registry entry with an unclassified extension is refused as
 *   `E-UNKNOWN-EXTENSION`, so `media: false` can no longer be asserted about a suffix
 *   there is nothing to check it against.
 * - An unregistered unclassified file under `public/assets/` is refused as
 *   `E-UNREGISTERED-MEDIA`, not `E-UNREGISTERED-FILE`: Vite copies `public/` into the
 *   build verbatim, so an unclassified file there ships whatever it is.
 * - A module under `src/` that names an unclassified extension is refused as
 *   `E-UNREGISTERED-SOURCE-MEDIA`, because the bundler resolves `./icon.svgz` exactly
 *   as it resolves `./icon.png`.
 * - The extension is not the only evidence. A `media: false` file whose bytes open with
 *   a known media container signature is refused as `E-MEDIA-SIGNATURE`, so a real
 *   image renamed `.md` is caught by the bytes even when the suffix is legal.
 *
 * The one deliberate exception, so it is not mistaken for a hole: a file under `src/`
 * that no module names and whose extension is unclassified is *skipped* rather than
 * refused. Vite emits a source-root file only when the module graph reaches it, so such
 * a file cannot ship; it is skipped only after its bytes have been checked against the
 * same media signatures, and the count of skipped files is printed in the gate's
 * summary so a skip is on the record rather than invisible. A file nothing reaches is
 * not a licensing problem; a file the build emits is.
 *
 * Owned and asserted elsewhere: `cc0-media-extension-vocabulary.test.ts` owns the
 * vocabulary and the byte check, and `cc0-source-media-scope.test.ts` owns the
 * source-tree reachability rule. This file keeps the count pin, which is the part that
 * does not need a policy to state.
 */
