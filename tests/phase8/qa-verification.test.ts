const REMOTE_FONT_HOST_PATTERN = /fonts\.(?:googleapis|gstatic)\.com/i;

describe('neither the generated Cozy stylesheet nor the build declares a remote font', () => {
  it('the checked-in Cozy stylesheets declare no @font-face and no remote URL', () => {
    for (const file of [COZY_TOKENS_CSS, COZY_CSS]) {
      const source = readFileSync(file, 'utf8');
      expect(source, file).not.toContain('@font-face');
      expect(source, file).not.toMatch(/@import\s+url\(/);
      expect(source, file).not.toMatch(REMOTE_FONT_HOST_PATTERN);
      // No remote anything: the generated layer is the one place a future token
      // could reintroduce a third-party origin, because it is checked in rather
      // than produced by a dependency.
      expect(source, file).not.toMatch(/https?:\/\/(?!creativecommons\.org|github\.com)/);
    }
  });

  it('the build contains no @font-face, no bundled font binary, and no font host', () => {
    if (!existsSync(DIST)) {
      // The unit suite must not depend on a build having happened. The E2E suite
      // and `npm run check:budget:welcome` are the places this is measured against
      // a real artifact; here it is only asserted when one is present.
      expect(true, 'no dist/ present; the artifact assertions are skipped').toBe(true);
      return;
    }
    const files: string[] = [];
    const walk = (dir: string): void => {
      for (const entry of readdirSync(dir, { withFileTypes: true })) {
        const full = path.join(dir, entry.name);
        if (entry.isDirectory()) walk(full);
        else files.push(full);
      }
    };
    walk(DIST);
    expect(files.length, 'dist/ is empty; the build assertions would be vacuous').toBeGreaterThan(10);

    const fontBinary = /\.(?:woff2?|ttf|otf|eot)$/i;
    for (const file of files) {
      expect(path.basename(file), `${file} is a bundled font binary`).not.toMatch(fontBinary);
      if (!/\.(?:js|mjs|css|html|json)$/i.test(file)) continue;
      const source = readFileSync(file, 'utf8');
      expect(source, file).not.toContain('@font-face');
      expect(source, file).not.toMatch(REMOTE_FONT_HOST_PATTERN);
    }
  });

  it('the entry document names no remote origin at all', () => {
    const indexPath = path.join(DIST, 'index.html');
    if (!existsSync(indexPath)) return;
    const html = readFileSync(indexPath, 'utf8');
    // Every src/href a built document carries is either relative or a data/blob
    // URL. A remote one would be a runtime fetch the budget gate cannot see.
    const references = [...html.matchAll(/\b(?:src|href)="([^"]+)"/g)].map((match) => match[1]);
    expect(references.length, 'the built entry document has no asset references').toBeGreaterThan(0);
    for (const reference of references) {
      if (reference.startsWith('#')) continue;
      expect(reference, `${reference} is a remote reference`).not.toMatch(/^(?:[a-z][a-z0-9+.-]*:)?\/\//i);
    }
  });
});

