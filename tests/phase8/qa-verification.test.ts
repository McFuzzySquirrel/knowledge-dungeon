/**
 * Independent verification of the Phase 8 gates, by the QA engineer.
 *
 * The Phase 8 suite already has a lot of coverage. This file deliberately does
 * not duplicate it. It covers the properties an independent pass found were
 * *asserted nowhere*, and it does so by reading the real artifacts and by
 * running the real scripts, so a green result here is a measurement rather than a
 * restatement of the implementation's own opinion of itself.
 *
 * What is here, and why each piece was not already covered:
 *
 * 1. **The remote-font gate can fail.** `currentBuild.spec.ts` recorded the
 *    recognised legacy font requests and asserted nothing about them, so Phase
 *    8's "the app renders without remote font requests" had no failing state.
 *    The predicate now lives in `./support/remoteFontGate.ts` and this file is
 *    its negative control: the same exported function is fed a synthetic request
 *    and must throw, with a message that names no hostname. The text assertions
 *    afterwards prove the spec actually calls it, so the control cannot pass
 *    vacuously against a spec that stopped using it.
 *
 * 2. **The media and budget gates are not behind the Cozy flag.** Both are
 *    project-level gates. If either read `VITE_COZY_VISUALS`, rolling the flag
 *    off would switch the gate off with it - the one thing a licensing gate and a
 *    performance budget must never share a switch with. This file asserts the
 *    flag is absent from both scripts *and* runs each of them with the flag set
 *    to `true` and to `false` and requires identical outcomes.
 *
 * 3. **The published registry cannot carry learner data.** It is served
 *    publicly at `/assets/asset-licenses.json`. A closed key vocabulary plus a
 *    scan of every string value is the cheapest honest check: an unknown key
 *    fails, and so does anything shaped like a subject name, a note, a room
 *    identifier, an email address, or a UUID.
 *
 * 4. **The built artifact carries no remote font and no remote origin.** Read
 *    from `dist/`, not from source, because source is not what ships. The
 *    generated Cozy stylesheet is checked for the same two things, since it is
 *    checked into the tree and would survive a build that stopped importing it.
 *
 * 5. **The rollback is a rollback.** The three legacy theme blocks must be
 *    byte-identical to their pre-Phase-8 values, and the only change permitted in
 *    `:root` is the three font-stack lines the no-remote-font criterion requires.
 *    The "before" comes from a committed baseline fixture with its own re-derived
 *    digest, not from the checkout's history: `git show HEAD:src/styles.css` made
 *    the gate compare the stylesheet against itself the moment the change was
 *    committed, so it passed in a dirty working tree and failed in a checkout of
 *    the committed state. The 5,813 lines below the theme blocks are held to the
 *    same standard by a pinned digest of the pre-Phase-8 region, so "unchanged" is
 *    a fact about bytes rather than a claim about what a runner happened to fetch.
 *
 * 6. **The recorded media-extension set is pinned.** The CC0 checker's media list
 *    is what makes "new media cannot be added without CC0 metadata" a mechanical
 *    rule, and it is the set an unlisted suffix can slip past. Pinning the set
 *    means a future edit to it is a reviewed act rather than a quiet widening.
 *    See the known-gap note in this file's tail for what pinning does *not* fix.
 *
 * 7. **The six Cozy placeholders are genuinely procedural.** They are admitted to
 *    the `pixi-default` bundle on the strength of being generated by a committed
 *    script, so the generator is run in a scratch tree and its output compared
 *    byte-for-byte with what is committed, and run twice to confirm it is
 *    deterministic. A generator that does not reproduce its own output is a
 *    provenance claim with nothing under it, and the pinned SHA-256s would then
 *    be pinning an arbitrary file.
 *
 * Privacy: this file contains no learner data, makes no network request, and
 * spawns only `node` against the repository and scratch directories under the OS
 * temp dir. It reads no commit history, and it never writes to `public/`, `src/`,
 * `scripts/`, or `dist/`.
 */

