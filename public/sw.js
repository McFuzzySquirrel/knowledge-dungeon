/*
 * Knowledge Dungeon offline static-shell service worker (Phase 22).
 *
 * ============================================================================
 * HAND-WRITTEN. NO WORKBOX. NO DEPENDENCY. This file is not bundled or
 * transformed: it is copied from `public/` into `dist/` byte for byte on a build
 * whose `VITE_OFFLINE_SHELL` flag is on, and removed on a build where it is off.
 * ============================================================================
 *
 * ## What it is for
 *
 * Exactly one guarantee: a previously loaded app reloads with no network, renders
 * the shell, and leaves the learner's IndexedDB data untouched. Nothing else. There
 * is deliberately no offline write queue, no background sync, no runtime caching of
 * responses the app fetches, no push, and no install prompt.
 *
 * ## The fetch allowlist, and why it is strict
 *
 * `fetch` only ever calls `respondWith` for:
 *
 *   1. a same-origin GET whose mode is `navigate` (the HTML document), or
 *   2. a same-origin GET whose path the build-time manifest named as a shell asset.
 *
 * Everything else - every non-GET, every cross-origin request, every `/api/` or
 * `/uploads/` path, and every same-origin path the manifest did not name - falls
 * through with no `respondWith` at all. There is no cache read and no cache write
 * on that path. Cross-origin and non-GET requests are not merely uncached, they are
 * not even inspected.
 *
 * ## It never touches IndexedDB
 *
 * This file contains no `indexedDB` reference and no learner data of any kind. The
 * only cache keys it can ever write are the build-time asset paths in
 * `offline-shell-manifest.js`, which are emitted from `dist/index.html` and are
 * therefore shell HTML/JS/CSS/fonts and the manifest - never subjects, notes,
 * attachments, progression, statistics, preferences, or assistance.
 *
 * ## Versioned caches update without serving mixed versions
 *
 * The cache name carries the build version token from the manifest. `install`
 * precaches the whole shell with `cache.addAll`, which is atomic: one failed asset
 * aborts the install and the previous worker keeps serving, so a half-populated
 * cache is never activated. `activate` deletes every cache in this family that is
 * not the current one, so a stale shell cannot survive a deploy and two builds'
 * assets are never mixed. The document is network-first so an online reload always
 * observes the deployed HTML, and joins the current cache on success.
 *
 * ## Privacy
 *
 * No learner data appears in this file, in a cache key, in a cached URL, or in any
 * log or error. `install` and `activate` failures are left to the browser's own
 * service-worker lifecycle reporting and are not re-serialized here.
 */

// The build-time manifest, generated by `scripts/generate-offline-shell.mjs` from
// the emitted `index.html`. `importScripts` is what lets the version token and the
// asset allowlist stay build facts rather than values baked into this hand-written
// file.
importScripts('offline-shell-manifest.js');

const MANIFEST =
  self.__KD_OFFLINE_SHELL_MANIFEST__ ??
  Object.freeze({ version: 'unversioned', document: './', assets: [] });

/** Every cache this worker owns shares this prefix, and nothing else may use it. */
const CACHE_PREFIX = 'kd-offline-shell-';
const CACHE_NAME = `${CACHE_PREFIX}${MANIFEST.version}`;

/** The exact same-origin asset paths the build named. Membership is the allowlist. */
const SHELL_ASSET_PATHS = new Set(MANIFEST.assets);

/** The document path served on an offline navigation. */
const DOCUMENT_PATH = MANIFEST.document;

/**
 * Paths that are never shell assets, whatever else is true. An explicit deny list
 * as well as an allowlist: a manifest bug that somehow named one of these still
 * cannot cache it, and the fetch handler below never inspects them anyway.
 */
const FORBIDDEN_PATH_PREFIXES = ['/api/', '/uploads/'];

function isForbiddenPath(pathname) {
  return FORBIDDEN_PATH_PREFIXES.some(
    (prefix) => pathname === prefix.slice(0, -1) || pathname.startsWith(prefix),
  );
}

self.addEventListener('install', (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE_NAME);
      // Atomic by design: a rejected asset rejects `addAll`, the install fails, and
      // the previously active worker keeps serving a complete cache. A partial
      // shell is never made current.
      await cache.addAll(MANIFEST.assets);
      await self.skipWaiting();
    })(),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const cacheNames = await caches.keys();
      await Promise.all(
        cacheNames
          .filter((name) => name.startsWith(CACHE_PREFIX) && name !== CACHE_NAME)
          .map((name) => caches.delete(name)),
      );
      // Take control of already-open clients so the reload after this activation is
      // served by this worker rather than the network.
      await self.clients.claim();
    })(),
  );
});

/**
 * Matching options for a cached shell entry.
 *
 * `ignoreVary` is load-bearing rather than tidiness. A static host may answer a
 * same-origin asset with `Vary: Origin` (Vite's preview server does), while the
 * request the app makes for a module script carries an `Origin` header that the
 * precache request did not. Strict `Vary` matching would then miss a byte-identical
 * cached asset purely on that header - a real measured failure in this lane - so the
 * shell matches on URL and ignores `Origin`, which cannot change the identity of a
 * content-hashed shell file.
 */
const MATCH_OPTIONS = Object.freeze({ ignoreSearch: true, ignoreVary: true });

/** Network-first for the document, with the cached shell as the offline fallback. */
async function handleNavigation(request) {
  const cache = await caches.open(CACHE_NAME);
  try {
    const response = await fetch(request);
    if (response !== undefined && response.ok) {
      await cache.put(DOCUMENT_PATH, response.clone());
    }
    return response;
  } catch (error) {
    const cached = await cache.match(DOCUMENT_PATH, MATCH_OPTIONS);
    if (cached !== undefined) return cached;
    throw error;
  }
}

/** Cache-first for a named shell asset, storing only paths the manifest named. */
async function handleShellAsset(request) {
  const cache = await caches.open(CACHE_NAME);
  const cached = await cache.match(request, MATCH_OPTIONS);
  if (cached !== undefined) return cached;

  const response = await fetch(request);
  // The membership test is redundant with the caller's, and is kept so this
  // function is safe to call with any request: a path not named by the build can
  // never be written into this cache.
  if (response.ok && SHELL_ASSET_PATHS.has(new URL(request.url).pathname)) {
    await cache.put(request, response.clone());
  }
  return response;
}

self.addEventListener('fetch', (event) => {
  const request = event.request;

  if (request.method !== 'GET') return;

  let url;
  try {
    url = new URL(request.url);
  } catch {
    return;
  }

  if (url.protocol !== 'http:' && url.protocol !== 'https:') return;
  if (url.origin !== self.location.origin) return;
  if (isForbiddenPath(url.pathname)) return;

  if (request.mode === 'navigate') {
    event.respondWith(handleNavigation(request));
    return;
  }

  if (SHELL_ASSET_PATHS.has(url.pathname)) {
    event.respondWith(handleShellAsset(request));
    return;
  }

  // Not the shell. No `respondWith`, no cache read, no cache write: the browser
  // performs the request exactly as it would with no service worker at all.
});
